// Regenerates src/lib/invoice/assets.ts from assets/ (fonts and logo used in invoice PDFs).
// Embedding them in code keeps them inside the server bundle on Vercel. Run: node scripts/embed-invoice-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const b64 = (p) => readFileSync(new URL(`../assets/${p}`, import.meta.url)).toString('base64');
writeFileSync(new URL('../src/lib/invoice/assets.ts', import.meta.url), `// Generated by scripts/embed-invoice-assets.mjs — do not edit. Figtree: SIL Open Font License 1.1 (assets/fonts/OFL.txt).
export const FONT_REGULAR = '${b64('fonts/Figtree-Regular.ttf')}';
export const FONT_BOLD = '${b64('fonts/Figtree-Bold.ttf')}';
export const LOGO_PNG = '${b64('invoice-logo.png')}';
`);
console.log('src/lib/invoice/assets.ts written');
